CREATE TABLE IF NOT EXISTS agent (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(60)   NOT NULL,
    role             VARCHAR(160),
    provider         VARCHAR(20)   NOT NULL,
    model            VARCHAR(80),
    effort           VARCHAR(20),
    color            VARCHAR(7)    NOT NULL,
    body             VARCHAR(20)   NOT NULL,
    eyes             VARCHAR(20)   NOT NULL,
    antennas         BOOLEAN       DEFAULT FALSE,
    tools            VARCHAR(500),
    spec             TEXT,
    team_ids         VARCHAR(100),
    orchestrator     BOOLEAN       DEFAULT FALSE,
    desk_index       INT           NOT NULL,
    status           VARCHAR(20)   NOT NULL,
    completed_tasks  INT           DEFAULT 0,
    last_duration_ms BIGINT        DEFAULT 0
);

CREATE TABLE IF NOT EXISTS task (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_id    BIGINT        NOT NULL REFERENCES agent(id),
    title       VARCHAR(200)  NOT NULL,
    description TEXT,
    status      VARCHAR(20)   NOT NULL,
    progress    INT           DEFAULT 0,
    result      TEXT,
    created_at  TIMESTAMP     NOT NULL,
    started_at  TIMESTAMP,
    finished_at TIMESTAMP,
    parent_id   BIGINT,
    workspace   VARCHAR(500)
);
